# Информационное сообщение
# ==========================================

info() {
    echo "[INFO] $1"
}

# ==========================================
# Успешное выполнение
# ==========================================

success() {
    echo "[ OK ] $1"
}

# ==========================================
# Предупреждение
# ==========================================

warning() {
    echo "[WARN] $1"
}

# ==========================================
# Ошибка
# ==========================================

error() {
    echo "[ERROR] $1"
}