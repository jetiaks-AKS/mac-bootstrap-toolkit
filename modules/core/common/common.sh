#!/bin/bash

# ==========================================
# Статистика Toolkit
# ==========================================

SUCCESS_COUNT=0
WARNING_COUNT=0
ERROR_COUNT=0

# ==========================================
# Информационное сообщение
# ==========================================

info() {
    echo "[INFO] $1"
}

# ==========================================
# Успешное выполнение
# ==========================================

success() {
    echo "[ OK ] $1"
}

# ==========================================
# Предупреждение
# ==========================================

warning() {
    echo "[WARN] $1"
}

# ==========================================
# Ошибка
# ==========================================

error() {
    echo "[ERROR] $1"
}

# ==========================================
# Заголовок раздела
# ==========================================

section() {

    echo
    echo "=========================================="
    echo " $1"
    echo "=========================================="

}

# ==========================================
# Запуск модуля
# ==========================================

run_module() {

    local module_name="$1"
    local module_function="$2"

    section "$module_name"

    $module_function

    local result=$?

    case $result in

        0)
            ((SUCCESS_COUNT++))
            ;;

        1)
            ((WARNING_COUNT++))
            ;;

        2)
            ((ERROR_COUNT++))
            ;;

    esac

# ==========================================
# Итоги работы Toolkit
# ==========================================

show_summary() {

    section "Итоги"

    echo "Успешно       : $SUCCESS_COUNT"
    echo "Предупреждений: $WARNING_COUNT"
    echo "Ошибок        : $ERROR_COUNT"

}

}