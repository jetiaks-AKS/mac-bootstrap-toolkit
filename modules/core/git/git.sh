#!/bin/bash

# ==========================================
# Проверка Git
# ==========================================

is_git_installed() {

    command -v git >/dev/null 2>&1

}

# ==========================================
# Проверка модуля
# ==========================================

check_git() {

    info "Проверяю Git..."

    if is_git_installed; then
        success "Git уже установлен"
        return 0
    fi

    error "Git не найден"

    return 2

}