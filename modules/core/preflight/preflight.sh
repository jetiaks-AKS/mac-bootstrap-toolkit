#!/bin/bash

# ==========================================
# Internet
# ==========================================

check_internet() {

    info "Проверяю подключение к Интернету..."

    if ping -c 1 1.1.1.1 >/dev/null 2>&1; then

        success "Интернет доступен"
        return 0

    fi

    error "Нет подключения к Интернету"
    return 2

}
